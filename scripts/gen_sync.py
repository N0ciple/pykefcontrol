#!/usr/bin/env python3
"""Generate the synchronous client from the asynchronous one ("unasync").

    python scripts/gen_sync.py          # regenerate pykefcontrol/_sync/{client,transport}.py
    python scripts/gen_sync.py --check  # exit 1 if the generated files are stale (CI)

The async sources are written so that a purely mechanical translation is
enough: ``async def``/``async for``/``async with`` lose ``async``, ``await`` is
dropped, and a few names are swapped (see ``REPLACEMENTS``). The hand-written
HTTP backends (``_async/backend.py`` with aiohttp, ``_sync/backend.py`` with
urllib3) expose the same interface, which is what makes this possible.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FILES = ("transport.py", "client.py")

# Exact substrings, applied first.
SUBSTRINGS = (
    ("aiohttp.ClientSession", "urllib3.PoolManager"),
    ("import aiohttp", "import urllib3"),
    ('"""Asynchronous client', '"""Synchronous (blocking) client'),
    ("as an async context manager", "as a context manager"),
)
# Whole words.
REPLACEMENTS = {
    "KefAsyncClient": "KefClient",
    "AsyncTransport": "SyncTransport",
    "AsyncBackend": "SyncBackend",
    "AsyncEventQueue": "EventQueue",
    "AsyncIterator": "Iterator",
    "AsyncIterable": "Iterable",
    "AsyncGenerator": "Generator",
    "StopAsyncIteration": "StopIteration",
    "__aenter__": "__enter__",
    "__aexit__": "__exit__",
    "__aiter__": "__iter__",
    "__anext__": "__next__",
    "aclose": "close",
    "_async": "_sync",
}
SYNTAX = (
    (re.compile(r"\basync (def|for|with)\b"), r"\1"),
    (re.compile(r"\bawait "), ""),
)
WORDS = re.compile(r"\b(" + "|".join(map(re.escape, REPLACEMENTS)) + r")\b")


def header(name: str) -> str:
    return (
        f"# GENERATED by scripts/gen_sync.py from pykefcontrol/_async/{name} -- DO NOT EDIT.\n"
        "# Edit the async source and run `python scripts/gen_sync.py`.\n"
    )


def unasync(source: str) -> str:
    for old, new in SUBSTRINGS:
        source = source.replace(old, new)
    for pattern, repl in SYNTAX:
        source = pattern.sub(repl, source)
    return WORDS.sub(lambda m: REPLACEMENTS[m.group(1)], source)


def generate(name: str) -> str:
    source = (ROOT / "pykefcontrol" / "_async" / name).read_text(encoding="utf-8")
    return header(name) + unasync(source)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="only check, do not write")
    args = parser.parse_args()
    stale = []
    for name in FILES:
        target = ROOT / "pykefcontrol" / "_sync" / name
        content = generate(name)
        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current == content:
            continue
        stale.append(target)
        if not args.check:
            target.write_text(content, encoding="utf-8")
    if args.check and stale:
        print("Stale generated files:", *map(str, stale), sep="\n  ", file=sys.stderr)
        print("Run: python scripts/gen_sync.py", file=sys.stderr)
        return 1
    for target in stale:
        print(f"regenerated {target.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
